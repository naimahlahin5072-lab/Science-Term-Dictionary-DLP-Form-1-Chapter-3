let currentTopic = "All";


/* =====================================================
   SORT TERMS ALPHABETICALLY
===================================================== */

terms.sort((a, b) =>
    a.name.localeCompare(
        b.name,
        undefined,
        {
            sensitivity: "base"
        }
    )
);


/* =====================================================
   DISPLAY TERMS
===================================================== */

function displayTerms(list) {

    termsContainer.innerHTML = "";


    if (list.length === 0) {

        noResults.classList.remove("hidden");

        resultCount.textContent =
            "0 terms found";

        return;
    }


    noResults.classList.add("hidden");


    resultCount.textContent =
        `${list.length} term${list.length === 1 ? "" : "s"} found`;


    /*
        Group terms by first letter
    */

    const groups = {};


    list.forEach(term => {

        const letter =
            term.name
                .charAt(0)
                .toUpperCase();


        if (!groups[letter]) {

            groups[letter] = [];

        }


        groups[letter].push(term);

    });


    /*
        Create each alphabetical section
    */

    Object.keys(groups)
        .sort()
        .forEach(letter => {

            const section =
                document.createElement("div");

            section.className =
                "letter-section";


            section.innerHTML = `

                <div class="letter-title">
                    ${letter}
                </div>

                <div class="term-list"></div>

            `;


            const listContainer =
                section.querySelector(
                    ".term-list"
                );


            groups[letter].forEach(term => {

                const item =
                    document.createElement("div");


                item.className =
                    "term-item";


                item.innerHTML = `

                    <div class="term-name">
                        ${term.name}
                    </div>

                    <div class="term-topic">
                        ${term.topic}
                    </div>

                `;


                item.onclick = () =>
                    openTerm(term);


                listContainer.appendChild(item);

            });


            termsContainer.appendChild(section);

        });

}


/* =====================================================
   OPEN TERM
===================================================== */

function openTerm(term) {

    const related =
        term.related &&
        term.related.length > 0

            ? `
                <div class="related-box">

                    <strong>
                        🔗 Related Terms
                    </strong>

                    <p>
                        ${term.related.join(" • ")}
                    </p>

                </div>
              `

            : "";


    modalContent.innerHTML = `

        <span class="modal-topic">
            ${term.topic}
        </span>

        <h2>
            ${term.name}
        </h2>

        <div class="definition">

            <strong>
                Definition
            </strong>

            <p>
                ${term.definition}
            </p>

        </div>


        <div class="example-box">

            <strong>
                💡 Example
            </strong>

            <br><br>

            ${term.example}

        </div>


        ${related}

    `;


    modal.classList.remove("hidden");

}


/* =====================================================
   SEARCH
===================================================== */

function searchTerms() {

    const query =
        searchInput.value
            .toLowerCase()
            .trim();


    let filtered =
        terms.filter(term => {

            const searchableText = `

                ${term.name}

                ${term.topic}

                ${term.definition}

                ${term.example}

                ${(term.related || []).join(" ")}

            `.toLowerCase();


            return searchableText
                .includes(query);

        });


    /*
        Apply topic filter
    */

    if (currentTopic !== "All") {

        filtered =
            filtered.filter(term =>
                term.topic === currentTopic
            );

    }


    displayTerms(filtered);


    clearButton.style.display =
        query
            ? "block"
            : "none";
}


/* =====================================================
   CREATE TOPIC BUTTONS
===================================================== */

function createTopicButtons() {

    const topics = [

        "All",

        ...new Set(
            terms.map(term =>
                term.topic
            )
        )

    ];


    topicButtons.innerHTML = "";


    topics.forEach(topic => {

        const button =
            document.createElement("button");


        button.className =
            "topic-button";


        if (topic === currentTopic) {

            button.classList.add(
                "active"
            );

        }


        button.textContent =
            topic;


        button.onclick = () => {

            currentTopic =
                topic;


            document
                .querySelectorAll(
                    ".topic-button"
                )
                .forEach(btn =>
                    btn.classList.remove(
                        "active"
                    )
                );


            button.classList.add(
                "active"
            );


            searchTerms();

        };


        topicButtons.appendChild(
            button
        );

    });

}


/* =====================================================
   CLEAR SEARCH
===================================================== */

clearButton.onclick = () => {

    searchInput.value = "";

    currentTopic = "All";

    createTopicButtons();

    searchTerms();

    searchInput.focus();

};


